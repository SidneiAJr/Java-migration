package com.javel.migration;

import java.util.ArrayList;
import java.util.List;

public class TableBuilder {

    private final String tableName;
    private final List<String> columns = new ArrayList<>();

    public TableBuilder(String tableName) {
        this.tableName = tableName;
    }

    public TableBuilder id() {
        columns.add("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
        return this;
    }

    public TableBuilder string(String name) {
        columns.add(name + " VARCHAR(255) NOT NULL");
        return this;
    }

    public TableBuilder text(String name) {
        columns.add(name + " TEXT");
        return this;
    }

    public TableBuilder integer(String name) {
        columns.add(name + " INT NOT NULL");
        return this;
    }

    public TableBuilder bigInteger(String name) {
        columns.add(name + " BIGINT NOT NULL");
        return this;
    }

    public TableBuilder bool(String name) {
        columns.add(name + " BOOLEAN DEFAULT FALSE");
        return this;
    }

    public TableBuilder decimal(String name, int precision, int scale) {
        columns.add(name + " DECIMAL(" + precision + "," + scale + ") NOT NULL");
        return this;
    }

    public TableBuilder nullable() {
        String last = columns.remove(columns.size() - 1);
        columns.add(last.replace(" NOT NULL", ""));
        return this;
    }

    public TableBuilder unique() {
        String last = columns.remove(columns.size() - 1);
        columns.add(last + " UNIQUE");
        return this;
    }

    public TableBuilder defaultValue(String value) {
        String last = columns.remove(columns.size() - 1);
        columns.add(last + " DEFAULT " + value);
        return this;
    }

    public TableBuilder timestamps() {
        columns.add("created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
        columns.add("updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP");
        return this;
    }

    public String toSQL() {
        return "CREATE TABLE " + tableName + " (\n  " +
                String.join(",\n  ", columns) +
                "\n);";
    }

    public String getTableName() {
        return tableName;
    }
}
package com.javel;

import java.util.ArrayList;
import java.util.List;

public class TableBuilder {

    public enum Dialect { H2, MYSQL, POSTGRESQL }

    private final String tableName;
    private final List<String> columns = new ArrayList<>();
    private final List<String> columnNames = new ArrayList<>(); // novo
    private final Dialect dialect;

    public TableBuilder(String tableName, Dialect dialect) {
        this.tableName = tableName;
        this.dialect = dialect;
    }

    public TableBuilder(String tableName) {
        this(tableName, Dialect.H2);
    }

    public TableBuilder id() {
        switch (dialect) {
            case MYSQL      -> columns.add("id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY");
            case POSTGRESQL -> columns.add("id BIGSERIAL PRIMARY KEY");
            default         -> columns.add("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
        }
        columnNames.add("id");
        return this;
    }

    public TableBuilder string(String name) {
        columns.add(name + " VARCHAR(255) NOT NULL");
        columnNames.add(name);
        return this;
    }

    public TableBuilder text(String name) {
        columns.add(name + " TEXT");
        columnNames.add(name);
        return this;
    }

    public TableBuilder integer(String name) {
        columns.add(name + " INT NOT NULL");
        columnNames.add(name);
        return this;
    }

    public TableBuilder bigInteger(String name) {
        columns.add(name + " BIGINT NOT NULL");
        columnNames.add(name);
        return this;
    }

    public TableBuilder bool(String name) {
        columns.add(name + " BOOLEAN NOT NULL DEFAULT FALSE");
        columnNames.add(name);
        return this;
    }

    public TableBuilder decimal(String name, int precision, int scale) {
        columns.add(name + " DECIMAL(" + precision + "," + scale + ") NOT NULL");
        columnNames.add(name);
        return this;
    }

    public TableBuilder nullable() {
        String last = columns.remove(columns.size() - 1);
        columns.add(last.replace(" NOT NULL", ""));
        return this;
    }

    public TableBuilder unique() {
        String last = columns.remove(columns.size() - 1);
        columns.add(last + " UNIQUE");
        return this;
    }

    public TableBuilder defaultValue(String value) {
        String last = columns.remove(columns.size() - 1);
        String cleaned = last.replaceAll("DEFAULT \\S+", "").trim();
        columns.add(cleaned + " DEFAULT " + value);
        return this;
    }

    public TableBuilder timestamps() {
        columns.add("created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
        if (dialect == Dialect.MYSQL) {
            columns.add("updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP");
        } else {
            columns.add("updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP");
        }
        columnNames.add("created_at");
        columnNames.add("updated_at");
        return this;
    }

    public String toSQL() {
        return "CREATE TABLE " + tableName + " (\n  " +
                String.join(",\n  ", columns) +
                "\n);";
    }

    public String getTableName() { return tableName; }
    public List<String> getColumnNames() { return columnNames; } // novo
}